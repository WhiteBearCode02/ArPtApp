"""Small public synthetic vectors from the ACTUAL OpenCV 4.13.0 uint8 INTER_LINEAR.

No model/user image/large tensor is read or published. Expected complete output is
represented by SHA256 plus a few probes; source RGB is regenerated by an explicit
integer formula, not a version-dependent RNG. --check never rewrites the fixture.
"""
import argparse
import hashlib
import importlib.metadata
import json
from pathlib import Path
import sys

import cv2
import numpy as np

SHAPES = [(1, 1), (2, 2), (3, 2), (2, 3), (5, 7), (7, 5), (17, 13), (13, 17),
          (320, 240), (640, 480), (1280, 720), (720, 1280), (640, 640), (1280, 1280), (1, 640), (640, 1)]
PATTERNS = ("gradient", "checkerboard", "edge", "counter_random")
SEED = 0x12345678


def rgb_image(width, height, pattern):
    y, x, c = np.indices((height, width, 3), dtype=np.uint32)
    if pattern == "gradient":
        values = 37 * x + 17 * y + 53 * c + 11
    elif pattern == "checkerboard":
        values = ((x + y + c) % 2) * 255
    elif pattern == "edge":
        values = np.where(x < width // 2, 17 + 41 * c, 241 - 37 * c) + (y % 3)
    elif pattern == "counter_random":
        values = ((y * width + x) * 3 + c) ^ np.uint32(SEED)
        values ^= values >> 16
        values *= np.uint32(0x7feb352d)
        values ^= values >> 15
        values *= np.uint32(0x846ca68b)
        values ^= values >> 16
    else:
        raise ValueError("Unknown deterministic pattern")
    return (values & 255).astype(np.uint8)


def environment():
    return dict(pythonVersion=sys.version.split()[0], opencvVersion=cv2.__version__,
        opencvDistribution=importlib.metadata.version("opencv-python-headless"), numpyVersion=np.__version__,
        litertVersion=importlib.metadata.version("ai-edge-litert"), optimized=cv2.useOptimized(),
        ippEnabled=cv2.ipp.useIPP(), ippNotExact=cv2.ipp.useIPP_NotExact(), cpuFeatures=cv2.getCPUFeaturesLine(),
        buildInformationSha256=hashlib.sha256(cv2.getBuildInformation().encode()).hexdigest())


def generate():
    if cv2.__version__ != "4.13.0":
        raise ValueError("EXP03 reference requires actual cv2 4.13.0, not a guessed bilinear")
    cases = []
    optimized, ipp = cv2.useOptimized(), cv2.ipp.useIPP()
    for width, height in SHAPES:
        ratio = min(640 / width, 640 / height)
        rw, rh = round(width * ratio), round(height * ratio)
        left, top = round((640-rw)/2-.1), round((640-rh)/2-.1)
        for pattern in PATTERNS:
            rgb = rgb_image(width, height, pattern)
            resized = cv2.resize(rgb, (rw, rh), interpolation=cv2.INTER_LINEAR)
            # Diagnostic only. Keep the DEFAULT reference output, never switch it to make Kotlin pass.
            try:
                cv2.setUseOptimized(False)
                cv2.ipp.setUseIPP(False)
                scalar = cv2.resize(rgb, (rw, rh), interpolation=cv2.INTER_LINEAR)
            finally:
                cv2.setUseOptimized(optimized)
                cv2.ipp.setUseIPP(ipp)
            padded = np.full((640, 640, 3), 114, np.uint8)
            padded[top:top+rh, left:left+rw] = resized
            tensor = np.ascontiguousarray(padded.transpose(2, 0, 1)[None], dtype="<f4") / np.float32(255)
            probes = [[int(i), int(resized.reshape(-1)[i])] for i in sorted(set(
                [0, resized.size-1, resized.size//2] + [(j*7919+17) % resized.size for j in range(8)]))]
            cases.append(dict(id=f"{width}x{height}_{pattern}", width=width, height=height, pattern=pattern,
                resizedWidth=rw, resizedHeight=rh, padX=left, padY=top, seed=SEED,
                resizedRgbSha256=hashlib.sha256(resized.tobytes()).hexdigest(),
                inputTensorSha256=hashlib.sha256(tensor.tobytes()).hexdigest(), probes=probes,
                defaultVsUnoptimizedMismatches=int(np.count_nonzero(resized != scalar))))
    return dict(schemaVersion=1, purpose="SYNTHETIC_INTERPOLATION_ONLY_NOT_ACTUAL_MODEL_GOLDEN", environment=environment(),
        reference="OpenCV 4.13.0 uint8 RGB INTER_LINEAR default path; no user media/model", cases=cases)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    document = generate()
    if args.check:
        existing = json.loads(args.output.read_text(encoding="utf-8"))
        if existing["cases"] != document["cases"] or existing["environment"]["opencvVersion"] != cv2.__version__:
            raise SystemExit("INTERPOLATION_FIXTURE_DRIFT: no automatic overwrite or tolerance change")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        with args.output.open("x", encoding="utf-8") as stream:
            json.dump(document, stream, indent=2)
            stream.write("\n")
    print(f"OpenCV {cv2.__version__} synthetic vectors: {len(document['cases'])}; default/unoptimized differing cases: "
          f"{sum(c['defaultVsUnoptimizedMismatches'] != 0 for c in document['cases'])}")


if __name__ == "__main__":
    main()
